-- ترقية قاعدة بيانات موجودة مسبقاً (لا تحذف أي بيانات)
-- شغّل هذا الملف فقط إذا كانت قاعدة بياناتك منشأة قبل إضافة ميزة
-- "تصنيف وفلترة الإشعارات" (Notifications Type/Filter)
-- مثال للتشغيل: mysql -u root -p اسم_قاعدة_البيانات < migration_notifications.sql
-- ============================================================

ALTER TABLE `notifications`
  ADD COLUMN `type` ENUM('machine','file','workday') NOT NULL DEFAULT 'file'
  COMMENT 'تصنيف حسب مصدر الحدث'
  AFTER `message`;

ALTER TABLE `notifications`
  ADD KEY `idx_type` (`type`);

-- ملاحظة: كل الإشعارات القديمة الموجودة مسبقاً في قاعدة بياناتك ستُصنَّف
-- تلقائياً كـ'file' (القيمة الافتراضية) لأنه لا توجد طريقة موثوقة لمعرفة
-- مصدرها الأصلي من نص الرسالة وحده. هذا لا يؤثر على أي إشعار جديد بعد الترقية،
-- فكل الإشعارات الجديدة ستُصنَّف بدقة من الكود مباشرة (machine/file/workday).
